// The map kit (src/code/map/kit.mjs): real Natural Earth outlines for land() and geo(), which the renderer gives the kit
// (src/canvas.mjs); without them (the validator's checks) every country is drawn as its box, which measures the same.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { CANVAS_STAGE, codeExtent, codeSceneErrors, runCodeScene, sampleInputs } from '../src/code/scene.mjs';
import { handTracedPoints, landPath, geoPoint, provideMapShapes } from '../src/code/map/kit.mjs';
import { MAP_COUNTRIES, MAP_UNIT } from '../src/code/map/countries.mjs';
import { MAP_SHAPES } from '../src/code/map/shapes.mjs';
import { KIT, OUTPUTS, builderHash } from '../scripts/build-map-kit.mjs';

const read = p => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const plain = value => JSON.parse(JSON.stringify(value));
const STAGE = [60, 250, 900, 1030];
const numbers = d => (d.match(/-?\d*\.?\d+/g) ?? []).map(Number);
const boxOf = d => { const n = numbers(d), xs = n.filter((_, i) => i % 2 === 0), ys = n.filter((_, i) => i % 2 === 1); return [Math.min(...xs), Math.min(...ys), Math.max(...xs), Math.max(...ys)]; };
const rings = d => d.split('M').filter(Boolean).map(r => { const n = numbers(r), pts = []; for (let i = 0; i + 1 < n.length; i += 2) pts.push([n[i], n[i + 1]]); return pts; });
const inside = (d, [x, y]) => {
  let c = false;
  for (const ring of rings(d)) for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) { const [xi, yi] = ring[i], [xj, yj] = ring[j]; if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c; }
  return c;
};
// The renderer's kit (with the outlines) for the length of `f`; the checks' kit (boxes) otherwise.
const outlined = f => { provideMapShapes(MAP_SHAPES); try { return f(); } finally { provideMapShapes(null); } };

test('the generated map kit is named in its header, sourced, and as the builder makes it', () => {
  for (const file of Object.values(OUTPUTS)) {
    const head = read(file).split('\n').slice(0, 7).join('\n');
    assert.match(head, new RegExp(`^// Generated by \`npm run map-kit\` \\(scripts/build-map-kit\\.mjs, builder ${builderHash()}\\)\\. Do not edit\\.`), file);
    assert.match(head, /Natural Earth 1:50m admin-0 countries \(public domain, naturalearthdata\.com\), via the world-atlas@2\.0\.2/);
  }
});

test('every country fits the scene limits, and the kit stays small', () => {
  const index = Buffer.byteLength(read(OUTPUTS.countries)), shapes = Buffer.byteLength(read(OUTPUTS.shapes));
  assert.ok(index < 16_000, `the index is ${index} bytes`);
  assert.ok(shapes > 120_000 && shapes < 250_000, `the outlines are ${shapes} bytes`);
  const codes = Object.keys(MAP_COUNTRIES);
  assert.ok(codes.length > 240, `${codes.length} codes`);
  assert.deepEqual(Object.keys(MAP_SHAPES).sort(), codes.slice().sort());
  for (const c of codes) {
    const box = landPath(c, ...STAGE);
    const path = outlined(() => landPath(c, ...STAGE));
    const points = rings(path).reduce((a, r) => a + r.length, 0);
    assert.ok(points <= KIT.maxPoints, `${c} has ${points} points`);
    assert.ok(path.length < 12000, `${c}'s path is ${path.length} characters`);
    // The checks' stand-in is exactly the box the outline reaches.
    assert.deepEqual(boxOf(box), boxOf(path), `${c}: the stand-in and the outline reach the same box`);
  }
  for (const c of ['FR', 'DE', 'US', 'US-AK', 'US-HI', 'GB', 'RU', 'CN', 'JP', 'BR', 'AQ', 'XK', 'CY', 'SO', 'PT-20', 'ES-CN', 'GF', 'TW', 'SG', 'VA']) assert.ok(MAP_COUNTRIES[c], c);
  // Far parts are their own codes, so a country fits its box: France without French Guiana, the US without Alaska.
  const lonOf = x => x / MAP_UNIT;
  assert.ok(lonOf(MAP_COUNTRIES.FR[0]) > -6 && lonOf(MAP_COUNTRIES.FR[2]) < 10, 'FR is metropolitan France');
  assert.ok(lonOf(MAP_COUNTRIES.US[0]) > -126, 'US is the lower 48');
});

test('land() draws real outlines where geo() puts their places', () => outlined(() => {
  const places = [['FR', 2.35, 48.86], ['DE', 13.4, 52.52], ['IT', 12.5, 41.9], ['CN', 116.4, 39.9], ['JP', 139.7, 35.7], ['AU', 149.13, -35.28], ['BR', -47.9, -15.8], ['US', -77.04, 38.9], ['US-AK', -149.9, 61.2], ['ZA', 28.19, -25.75], ['AQ', 0, -90], ['RU', 177, 65], ['LS', 27.48, -29.31]];
  for (const [c, lon, lat] of places) assert.ok(inside(landPath(c, ...STAGE), geoPoint(lon, lat, c, ...STAGE)), `${c} holds ${lon}, ${lat}`);
  assert.ok(!inside(landPath('ZA', ...STAGE), geoPoint(27.48, -29.31, 'ZA', ...STAGE)), 'Lesotho is a hole in South Africa');
  assert.ok(!inside(landPath('FR', ...STAGE), geoPoint(-0.13, 51.5, 'FR', ...STAGE)), 'London is not in France');
  // A country fits its box: aspect kept, centred, touching two opposite sides.
  const [x0, y0, x1, y1] = boxOf(landPath('CL', ...STAGE));
  assert.ok(Math.abs(y0 - 250) < 0.2 && Math.abs(y1 - 1280) < 0.2 && Math.abs((x0 + x1) / 2 - 510) < 0.2, 'Chile, tall, fills the height, centred');
  // Neighbours on one map meet on the same points.
  const map = ['FR', 'DE'];
  const fr = new Set(rings(landPath(map, ...STAGE, 'FR')).flat().map(p => p.join()));
  assert.ok(rings(landPath(map, ...STAGE, 'DE')).flat().filter(p => fr.has(p.join())).length >= 10, 'France and Germany share their border');
}));

test('an unknown code fails clearly, and the checks name what to write', () => {
  assert.throws(() => landPath('ZZ', ...STAGE), /land\('ZZ'\) isn't a country the map kit knows; use ISO 3166-1 alpha-2 codes/);
  assert.throws(() => landPath('UK', ...STAGE), /use 'GB' \(United Kingdom\)/);
  assert.throws(() => geoPoint(0, 0, 'Germany', ...STAGE), /geo\('Germany'\): use the country's ISO code, 'DE' for Germany/);
  const scene = `export default function Scene({ colors, stage }) {
  return <svg><path d={land('ZZ', stage.left, 300, 900, 900)} fill={colors.chalk}/></svg>;
}`;
  assert.match(codeSceneErrors('beat 2 (code)', scene, 'This is a map of nowhere at all.', new Set(), CANVAS_STAGE)[0], /^beat 2 \(code\): the code fails at 0\.0 s: land\('ZZ'\) isn't a country the map kit knows/);
});

// Alaska spreads in the accent from Anchorage on a map of the North Pacific, with Russia and Canada around it.
const ALASKA = `export default function Scene({ time, colors, stage }) {
  const map = ['US-AK', 'CA', 'RU', 'US'];
  const x = stage.left, y = stage.top + 150, w = stage.right - stage.left, h = 760;
  const p = easeOut(clamp((time - at('Alaska')) / 0.9));
  const [ax, ay] = geo(-149.9, 61.2, map, x, y, w, h);
  const coast = { stroke: colors.ink, strokeOpacity: 0.3, strokeWidth: 3 };
  return <svg>
    <rect x={0} y={0} width={1080} height={1920} fill={colors.wall}/>
    <defs><clipPath id="spread"><circle cx={ax} cy={ay} r={30 + 700 * p}/></clipPath></defs>
    <path d={land(map, x, y, w, h, ['RU', 'CA', 'US'])} fill={colors.chalk} {...coast}/>
    <path d={land(map, x, y, w, h, 'US-AK')} fill={colors.chalk} {...coast}/>
    <path d={land(map, x, y, w, h, 'US-AK')} fill={colors.accent} fillOpacity={0.7} clipPath="url(#spread)"/>
    <circle cx={ax} cy={ay} r={12} fill={colors.ink}/>
    <text x={ax + 24} y={ay + 12} fontSize={36} fontWeight={700}>ANCHORAGE</text>
    <text x={stage.left + 10} y={stage.top + 70} fontSize={64} fontWeight={700}>1867</text>
  </svg>;
}`;
const LINE = 'In 1867, the United States bought Alaska from Russia for seven point two million dollars.';

test('a map scene of four countries passes the checks, with or without the outlines, and measures the same', () => {
  assert.deepEqual(plain(codeSceneErrors('beat 1 (code)', ALASKA, LINE, new Set(), CANVAS_STAGE)), []);
  assert.deepEqual(plain(outlined(() => codeSceneErrors('beat 1 (code)', ALASKA, LINE, new Set(), CANVAS_STAGE))), [], 'the outlines pass the same checks');
  const inputs = sampleInputs(LINE, CANVAS_STAGE);
  const boxes = runCodeScene(ALASKA, { ...inputs, time: inputs.duration });
  const tree = outlined(() => runCodeScene(ALASKA, { ...inputs, time: inputs.duration }));
  const paths = [];
  const walk = n => { if (!n || typeof n !== 'object') return; if (Array.isArray(n)) return n.forEach(walk); if (n.tag === 'path') paths.push(n.props.d); n.children.forEach(walk); };
  walk(tree);
  assert.equal(paths.length, 3);
  assert.ok(paths.every(d => d.length < 12000 && d.length > 1000), 'each land() is a real outline under the text limit');
  assert.deepEqual(plain(codeExtent(boxes, { drawn: true })), plain(codeExtent(tree, { drawn: true })));
});

test('an outline traced by hand is sent back to the map kit', () => {
  const trace = n => Array.from({ length: n }, (_, i) => `${Math.round(540 + 380 * Math.cos(i / n * 6.283))} ${Math.round(800 + 380 * Math.sin(i / n * 6.283) * (1 + 0.1 * Math.sin(i)))}`).join(' L ');
  const scene = points => `export default function Scene({ colors }) {
  return <svg><path d="M ${trace(points)} Z" fill={colors.chalk}/><text x={540} y={1240} fontSize={60} textAnchor="middle">France</text></svg>;
}`;
  const line = 'This is the outline of France.';
  assert.match(codeSceneErrors('beat 3 (code)', scene(70), line, new Set(), CANVAS_STAGE).join('\n'), /beat 3 \(code\): an outline here is traced by hand with 70 points; .*draw it with the map kit: land\('FR', x, y, w, h\)/);
  assert.ok(!codeSceneErrors('beat 3 (code)', scene(40), line, new Set(), CANVAS_STAGE).some(e => /traced by hand/.test(e)), 'a 40-point shape is a drawing');
  assert.equal(handTracedPoints(`const pts = [${Array.from({ length: 64 }, (_, i) => `[${i * 10}, ${i * 7}]`).join(', ')}];`), 64, 'a list of [x, y] pairs');
  assert.equal(handTracedPoints(`<path d={'M ' + x + ' ' + y + ' L ' + (x + 10) + ' ' + y}/>`), 0, 'a shape built from values');
});
